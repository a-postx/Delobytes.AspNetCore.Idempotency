namespace Delobytes.AspNetCore.Idempotency;

/// <summary>
/// <para>
/// Состояние записи идемпотентного запроса в кеше.
/// </para>
/// <para>
/// Используется для защиты от гонки параллельных дублирующихся запросов:
/// когда два одинаковых запроса с одним Idempotency-Key прилетают почти одновременно,
/// первый помечает запрос как InProgress, второй видит этот статус и ждёт (или возвращает 425 Too Early).
/// После завершения обработки первого запроса статус меняется на Completed с финальным результатом.
/// </para>
/// </summary>
public enum IdempotencyRequestStatus
{
    /// <summary>
    /// Статус не определён или запись повреждена.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Запрос находится в процессе обработки. Используется для защиты от параллельных гонок.
    /// Если параллельный запрос получит этот статус, он должен либо дождаться завершения,
    /// либо вернуть 425 Too Early (в зависимости от конфигурации).
    /// </summary>
    InProgress = 1,

    /// <summary>
    /// Обработка запроса завершена, результат готов к воспроизведению.
    /// </summary>
    Completed = 2
}
